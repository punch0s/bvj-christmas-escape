from pathlib import Path
import json,hashlib
root=Path(__file__).resolve().parent
names=['index.html','animation.html','manifest.json','icons/icon-192.png','icons/icon-512.png']
assets=[{'path':'./'+n,'hash':hashlib.sha256((root/n).read_bytes()).hexdigest()} for n in names]
version=hashlib.sha256(json.dumps(assets,sort_keys=True).encode()).hexdigest()[:12]
worker="""// Generated by python3 build_release.py; upload the whole release together.
const VERSION=__VERSION__;
const PREFIX='bvj-escape-'+new URL(self.registration.scope).pathname+'-';
const CACHE=PREFIX+VERSION;
const ASSETS=__ASSETS__;
self.addEventListener('install',event=>event.waitUntil((async()=>{
 const cache=await caches.open(CACHE);
 try{for(const asset of ASSETS){
  const canonical=new URL(asset.path,self.registration.scope),fresh=new URL(canonical);fresh.searchParams.set('v',VERSION);
  const response=await fetch(fresh,{cache:'reload'});if(!response.ok)throw new Error('Missing '+asset.path);
  const hash=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',await response.clone().arrayBuffer())),b=>b.toString(16).padStart(2,'0')).join('');
  if(hash!==asset.hash)throw new Error('Incomplete release '+asset.path);await cache.put(canonical,response);
 }}catch(error){await caches.delete(CACHE);throw error;}
})()));
// Existing clients activate updates explicitly so no active run is interrupted.
self.addEventListener('message',event=>{if(event.data?.type==='SKIP_WAITING')event.waitUntil(self.skipWaiting());});
self.addEventListener('activate',event=>event.waitUntil((async()=>{
 for(const name of await caches.keys())if(name.startsWith(PREFIX)&&name!==CACHE)await caches.delete(name);
 await self.clients.claim();
})()));
self.addEventListener('fetch',event=>{
 const url=new URL(event.request.url);if(event.request.method!=='GET'||url.origin!==self.location.origin)return;
 event.respondWith((async()=>{
  const key=new URL(url.pathname,url.origin),scopeRoot=new URL('./',self.registration.scope);
  if(event.request.mode==='navigate'&&key.href===scopeRoot.href)key.pathname+='index.html';
  const saved=await (await caches.open(CACHE)).match(key);return saved||fetch(event.request);
 })());
});
""".replace('__VERSION__',repr(version)).replace('__ASSETS__',json.dumps(assets,separators=(',',':')))
(root/'sw.js').write_text(worker);(root/'release.json').write_text(json.dumps({'version':version,'assets':assets},indent=2));print('Release',version)
